create or replace function public.revenue_academic_month_number(p_month text)
returns smallint
language sql
immutable
strict
as $$
  select case lower(btrim(p_month))
    when 'jul' then 1
    when 'aug' then 2
    when 'sep' then 3
    when 'oct' then 4
    when 'nov' then 5
    when 'dec' then 6
    when 'jan' then 7
    when 'feb' then 8
    when 'mar' then 9
    when 'apr' then 10
    when 'may' then 11
    when 'jun' then 12
    else null
  end::smallint;
$$;

create or replace function public.revenue_academic_month_label(p_month_number smallint)
returns text
language sql
immutable
strict
as $$
  select case p_month_number
    when 1 then 'Jul'
    when 2 then 'Aug'
    when 3 then 'Sep'
    when 4 then 'Oct'
    when 5 then 'Nov'
    when 6 then 'Dec'
    when 7 then 'Jan'
    when 8 then 'Feb'
    when 9 then 'Mar'
    when 10 then 'Apr'
    when 11 then 'May'
    when 12 then 'Jun'
    else null
  end;
$$;

