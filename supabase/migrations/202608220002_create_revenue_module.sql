create or replace function public.import_revenue_annual_targets(p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare v_imported bigint := 0;
begin
  if jsonb_typeof(p_rows) <> 'array' then raise exception 'p_rows harus berupa JSON array'; end if;
  insert into public.t_revenue_annual_target (academic_year, branch_id, target_revenue)
  select x.academic_year, x.branch_id, x.target_revenue
  from jsonb_to_recordset(p_rows) as x(
    academic_year text, branch_id integer, target_revenue bigint
  )
  on conflict (academic_year, branch_id) do update
  set target_revenue = excluded.target_revenue, updated_at = now();
  get diagnostics v_imported = row_count;
  return jsonb_build_object('imported_rows', v_imported);
end;
$$;

