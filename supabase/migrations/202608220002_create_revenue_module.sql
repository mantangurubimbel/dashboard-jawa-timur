create or replace function public.get_revenue_dashboard_v2(
  p_academic_year text default null,
  p_region_id integer default null,
  p_branch_id integer default null,
  p_month text default null,
  p_from_date date default null,
  p_to_date date default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_current_year text := coalesce(
    p_academic_year,
    (select academic_year from public.t_academic_year where is_active order by academic_year desc limit 1)
  );
  v_ly_year text;
  v_l2y_year text;
  v_start_date date;
  v_end_date date;
  v_ly_start date;
  v_ly_end date;
  v_l2y_start date;
  v_l2y_end date;
  v_month_number smallint;
  v_target numeric := 0;
  v_current numeric := 0;
  v_ly numeric := 0;
  v_l2y numeric := 0;
  v_result jsonb;
begin
  v_ly_year := lpad(((split_part(v_current_year, '/', 1)::integer + 99) % 100)::text, 2, '0')
    || '/' || split_part(v_current_year, '/', 1);
  v_l2y_year := lpad(((split_part(v_current_year, '/', 1)::integer + 98) % 100)::text, 2, '0')
    || '/' || lpad(((split_part(v_current_year, '/', 1)::integer + 99) % 100)::text, 2, '0');
  if not exists (select 1 from public.t_academic_year where academic_year = v_ly_year) then v_ly_year := null; end if;
  if not exists (select 1 from public.t_academic_year where academic_year = v_l2y_year) then v_l2y_year := null; end if;

  v_start_date := make_date(2000 + split_part(v_current_year, '/', 1)::integer, 7, 1);
  v_end_date := make_date(2000 + split_part(v_current_year, '/', 2)::integer, 6, 30);

  if p_month is not null then
    v_month_number := public.revenue_academic_month_number(p_month);
    if v_month_number is null then raise exception 'Bulan tidak valid: %', p_month; end if;
    v_start_date := make_date(
      case when v_month_number <= 6 then 2000 + split_part(v_current_year, '/', 2)::integer
           else 2000 + split_part(v_current_year, '/', 1)::integer end,
      case when v_month_number <= 6 then v_month_number + 6 else v_month_number - 6 end,
      1
    );
    v_end_date := (date_trunc('month', v_start_date) + interval '1 month - 1 day')::date;
  end if;

  v_start_date := greatest(v_start_date, coalesce(p_from_date, v_start_date));
  v_end_date := least(v_end_date, coalesce(p_to_date, v_end_date));
  v_ly_start := (v_start_date - interval '1 year')::date;
  v_ly_end := (v_end_date - interval '1 year')::date;
  v_l2y_start := (v_start_date - interval '2 years')::date;
  v_l2y_end := (v_end_date - interval '2 years')::date;

  select
    coalesce(sum(tx.revenue) filter (where tx.academic_year = v_current_year and tx.payment_date between v_start_date and v_end_date), 0),
    coalesce(sum(tx.revenue) filter (where v_ly_year is not null and tx.academic_year = v_ly_year and tx.payment_date between v_ly_start and v_ly_end), 0),
    coalesce(sum(tx.revenue) filter (where v_l2y_year is not null and tx.academic_year = v_l2y_year and tx.payment_date between v_l2y_start and v_l2y_end), 0)
  into v_current, v_ly, v_l2y
  from public.t_revenue_txn tx
  join public.t_branch b on b.branch_id = tx.branch_id
  where (tx.payment_date between v_start_date and v_end_date
    or tx.payment_date between v_ly_start and v_ly_end
    or tx.payment_date between v_l2y_start and v_l2y_end)
    and (p_region_id is null or b.region_id = p_region_id)
    and (p_branch_id is null or tx.branch_id = p_branch_id);

  select coalesce(sum(t.target_revenue), 0)
  into v_target
  from public.t_revenue_annual_target t
  join public.t_branch b on b.branch_id = t.branch_id
  where t.academic_year = v_current_year
    and (p_region_id is null or b.region_id = p_region_id)
    and (p_branch_id is null or t.branch_id = p_branch_id);

  with
  months(month_label, month_number) as (
    values ('Jul',1),('Aug',2),('Sep',3),('Oct',4),('Nov',5),('Dec',6),
           ('Jan',7),('Feb',8),('Mar',9),('Apr',10),('May',11),('Jun',12)
  ),
  actual(month_label, revenue, transactions) as (
    select split_part(tx.month, ' ', 1), sum(tx.revenue), count(*)
    from public.t_revenue_txn tx
    join public.t_branch b on b.branch_id = tx.branch_id
      where tx.academic_year = v_current_year
      and tx.payment_date between v_start_date and v_end_date
      and (p_region_id is null or b.region_id = p_region_id)
      and (p_branch_id is null or tx.branch_id = p_branch_id)
    group by split_part(tx.month, ' ', 1)
  ),
  ly(month_label, revenue) as (
    select split_part(tx.month, ' ', 1), sum(tx.revenue)
    from public.t_revenue_txn tx
    join public.t_branch b on b.branch_id = tx.branch_id
      where v_ly_year is not null
      and tx.academic_year = v_ly_year
      and tx.payment_date between v_ly_start and v_ly_end
      and (p_region_id is null or b.region_id = p_region_id)
      and (p_branch_id is null or tx.branch_id = p_branch_id)
    group by split_part(tx.month, ' ', 1)
  ),
  l2y(month_label, revenue) as (
    select split_part(tx.month, ' ', 1), sum(tx.revenue)
    from public.t_revenue_txn tx
    join public.t_branch b on b.branch_id = tx.branch_id
      where v_l2y_year is not null
      and tx.academic_year = v_l2y_year
      and tx.payment_date between v_l2y_start and v_l2y_end
      and (p_region_id is null or b.region_id = p_region_id)
      and (p_branch_id is null or tx.branch_id = p_branch_id)
    group by split_part(tx.month, ' ', 1)
  ),
  targets(month_number, revenue) as (
    select t.month_number, sum(t.target_revenue)
    from public.t_revenue_monthly_target t
    join public.t_branch b on b.branch_id = t.branch_id
    where t.academic_year = v_current_year
      and (p_region_id is null or b.region_id = p_region_id)
      and (p_branch_id is null or t.branch_id = p_branch_id)
    group by t.month_number
  ),
  monthly as (
    select
      m.month_label,
      m.month_number,
      coalesce(a.revenue,0)::numeric current_revenue,
      coalesce(a.transactions,0)::integer current_transactions,
      case when v_ly_year is null then null else coalesce(y.revenue,0)::numeric end ly_revenue,
      case when v_l2y_year is null then null else coalesce(z.revenue,0)::numeric end l2y_revenue,
      coalesce(t.revenue,0)::numeric target_revenue
    from months m
    left join actual a on a.month_label = m.month_label
    left join ly y on y.month_label = m.month_label
    left join l2y z on z.month_label = m.month_label
    left join targets t on t.month_number = m.month_number
  ),
  cumulative as (
    select *,
      sum(current_revenue) over (order by month_number) current_cumulative_revenue,
      case when v_ly_year is null then null else sum(ly_revenue) over (order by month_number) end ly_cumulative_revenue,
      case when v_l2y_year is null then null else sum(l2y_revenue) over (order by month_number) end l2y_cumulative_revenue,
      sum(target_revenue) over (order by month_number) target_cumulative_revenue
    from monthly
  )
  select jsonb_build_object(
      'kpis', jsonb_build_object(
      'totalRevenue', v_current,
      'totalTransactions', coalesce((select sum(current_transactions) from monthly),0),
      'uniqueInvoices', 0,
      'activeBranches', 0,
      'activeAgents', 0,
      'knownSchools', 0,
      'averageOrderValue', 0,
      'nonBulkRevenue', 0,
      'nonBulkNewTransactions', 0,
      'targetAnnualRevenue', v_target,
      'achievement', case when v_target = 0 then null else v_current / v_target end,
      'varianceToTarget', v_current - v_target,
      'growthVsLy', case when v_ly = 0 then null else v_current / v_ly end,
      'growthVsL2y', case when v_l2y = 0 then null else v_current / v_l2y end
    ),
    'monthlyRevenue', coalesce((select jsonb_agg(jsonb_build_object('name', month_label, 'period', month_label, 'revenue', current_revenue, 'transactions', current_transactions) order by month_number) from cumulative), '[]'::jsonb),
    'monthlyRevenueComparison', jsonb_build_object(
      'currentAcademicYear', v_current_year,
      'previousAcademicYear', v_ly_year,
      'rows', coalesce((select jsonb_agg(jsonb_build_object(
        'month', month_label,
        'currentRevenue', current_revenue,
        'currentCumulativeRevenue', current_cumulative_revenue,
        'currentTransactions', current_transactions,
        'previousRevenue', ly_revenue,
