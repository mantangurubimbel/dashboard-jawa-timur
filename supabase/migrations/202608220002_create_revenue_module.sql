create or replace function public.replace_revenue_txn_by_dates(p_rows jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_dates date[];
  v_deleted bigint := 0;
  v_inserted bigint := 0;
begin
  if jsonb_typeof(p_rows) <> 'array' then
    raise exception 'p_rows harus berupa JSON array';
  end if;

  select array_agg(distinct x.payment_date order by x.payment_date)
  into v_dates
  from jsonb_to_recordset(p_rows) as x(payment_date date);

  if coalesce(array_length(v_dates, 1), 0) = 0 then
    return jsonb_build_object('replaced_dates', 0, 'deleted_rows', 0, 'inserted_rows', 0);
  end if;

  delete from public.t_revenue_txn
  where payment_date = any(v_dates);
  get diagnostics v_deleted = row_count;

  insert into public.t_revenue_txn (
    payment_date, month, invoice, grade_id, product_id, agent_id,
    branch_destination_id, branch_id, is_newtxn, is_fullpayment,
    academic_year, npsn, revenue, is_bulkbuying
  )
  select
    x.payment_date, x.month, x.invoice, x.grade_id, x.product_id, x.agent_id,
    x.branch_destination_id, x.branch_id, x.is_newtxn, x.is_fullpayment,
    x.academic_year, x.npsn, x.revenue, x.is_bulkbuying
  from jsonb_to_recordset(p_rows) as x(
    payment_date date, month text, invoice text, grade_id integer,
    product_id integer, agent_id integer, branch_destination_id integer,
    branch_id integer, is_newtxn boolean, is_fullpayment boolean,
    academic_year text, npsn text, revenue integer, is_bulkbuying boolean
  );
  get diagnostics v_inserted = row_count;

  return jsonb_build_object(
    'replaced_dates', cardinality(v_dates),
    'deleted_rows', v_deleted,
    'inserted_rows', v_inserted,
    'dates', to_jsonb(v_dates)
  );
end;
$$;

