create or replace view public.v_revenue_annual_target_by_region
with (security_invoker = true)
as
select
  t.academic_year,
  b.region_id,
  r.region_name,
  sum(t.target_revenue)::bigint as target_revenue
from public.t_revenue_annual_target t
join public.t_branch b on b.branch_id = t.branch_id
join public.t_region r on r.region_id = b.region_id
group by t.academic_year, b.region_id, r.region_name;

